-- =============================================================================
--  0130_repoint_rows_on_merged_items   (DATA, shared)
--
--  2026-11-02, after 0129. Rows in Kount's own mapping tables (and a small
--  KevaOS tail) still point at ARCHIVED items whose merged_into_id resolves to
--  a live item, so a recompute splits one product into two report lines
--  (purchases on one, counts on the other) and recount corrections / POS
--  depletions land on the archived copy. Found: invoice placement maps 45+18,
--  price fingerprints 41, POS ingredient map 193, recounts 53, carried 660,
--  barcode requests 466, prices 9, entries 2, transfers 7; KevaOS
--  invoice_lines 180 + menu map 1.
--
--  Moves every such row to resolve_master_item(archived id). Where the live
--  item already has a row under the same key, the archived copy's row is
--  dropped (it duplicates the live one). Every changed row is saved whole in
--  _mig0130_log first. KevaOS tables go through repoint_master_refs.
--  item_par_calculations (KevaOS PAR, regenerated by its own job) untouched.
--  ROLLBACK: 0130_ROLLBACK_repoint_rows_on_merged_items.sql
-- =============================================================================
begin;

create table if not exists public._mig0130_log (id bigserial primary key, table_name text not null, action text not null, row jsonb not null, old_master uuid, new_master uuid);
alter table public._mig0130_log enable row level security;
revoke all on public._mig0130_log from anon, authenticated;

create temp table _dead on commit drop as
  select m.id, public.resolve_master_item(m.id) as live
    from public.master_items m join public.master_items s on s.id = m.merged_into_id
   where not m.is_active and s.is_active;
delete from _dead d where d.live = d.id or not exists (select 1 from public.master_items x where x.id = d.live and x.is_active);
create index on _dead (id);

-- ---- simple tables: master_item_id is not part of any unique key -----------
insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_entries', 'moved', to_jsonb(t), d.id, d.live from public.kount_entries t join _dead d on d.id = t.master_item_id;
update public.kount_entries t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_recounts', 'moved', to_jsonb(t), d.id, d.live from public.kount_recounts t join _dead d on d.id = t.master_item_id;
update public.kount_recounts t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'new_recipe_ingredient_master_map', 'moved', to_jsonb(t), d.id, d.live from public.new_recipe_ingredient_master_map t join _dead d on d.id = t.master_item_id;
update public.new_recipe_ingredient_master_map t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'upc_mappings', 'moved', to_jsonb(t), d.id, d.live from public.upc_mappings t join _dead d on d.id = t.master_item_id;
update public.upc_mappings t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'transfer_lines', 'moved', to_jsonb(t), d.id, d.live from public.transfer_lines t join _dead d on d.id = t.master_item_id;
update public.transfer_lines t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

-- ---- keyed tables: move if the live item has no row under the key, else drop
insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_carried_items', case when exists (select 1 from public.kount_carried_items k where k.master_item_id = d.live) then 'deleted' else 'moved' end, to_jsonb(t), d.id, d.live
  from public.kount_carried_items t join _dead d on d.id = t.master_item_id;
delete from public.kount_carried_items t using _dead d where d.id = t.master_item_id and exists (select 1 from public.kount_carried_items k where k.master_item_id = d.live);
-- several archived rows can resolve to the same live item: keep one
delete from public.kount_carried_items t using _dead d where d.id = t.master_item_id
   and t.id <> (select min(t2.id::text)::uuid from public.kount_carried_items t2 join _dead d2 on d2.id = t2.master_item_id where d2.live = d.live);
update public.kount_carried_items t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_cost_overrides', case when exists (select 1 from public.kount_cost_overrides k where k.master_item_id = d.live) then 'deleted' else 'moved' end, to_jsonb(t), d.id, d.live
  from public.kount_cost_overrides t join _dead d on d.id = t.master_item_id;
delete from public.kount_cost_overrides t using _dead d where d.id = t.master_item_id and exists (select 1 from public.kount_cost_overrides k where k.master_item_id = d.live);
update public.kount_cost_overrides t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_venue_cost_overrides', case when exists (select 1 from public.kount_venue_cost_overrides k where k.venue_id = t.venue_id and k.master_item_id = d.live) then 'deleted' else 'moved' end, to_jsonb(t), d.id, d.live
  from public.kount_venue_cost_overrides t join _dead d on d.id = t.master_item_id;
delete from public.kount_venue_cost_overrides t using _dead d where d.id = t.master_item_id
   and exists (select 1 from public.kount_venue_cost_overrides k where k.venue_id = t.venue_id and k.master_item_id = d.live);
update public.kount_venue_cost_overrides t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_invoice_item_map', case when exists (select 1 from public.kount_invoice_item_map k where k.venue_id = t.venue_id and k.purchase_item_id = t.purchase_item_id and k.master_item_id = d.live) then 'deleted' else 'moved' end, to_jsonb(t), d.id, d.live
  from public.kount_invoice_item_map t join _dead d on d.id = t.master_item_id;
delete from public.kount_invoice_item_map t using _dead d where d.id = t.master_item_id
   and exists (select 1 from public.kount_invoice_item_map k where k.venue_id = t.venue_id and k.purchase_item_id = t.purchase_item_id and k.master_item_id = d.live);
update public.kount_invoice_item_map t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_invoice_line_map', case when exists (select 1 from public.kount_invoice_line_map k where k.venue_id = t.venue_id and k.invoice_line_id = t.invoice_line_id and k.master_item_id = d.live) then 'deleted' else 'moved' end, to_jsonb(t), d.id, d.live
  from public.kount_invoice_line_map t join _dead d on d.id = t.master_item_id;
delete from public.kount_invoice_line_map t using _dead d where d.id = t.master_item_id
   and exists (select 1 from public.kount_invoice_line_map k where k.venue_id = t.venue_id and k.invoice_line_id = t.invoice_line_id and k.master_item_id = d.live);
update public.kount_invoice_line_map t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

insert into public._mig0130_log (table_name, action, row, old_master, new_master)
select 'kount_price_fingerprints', case when exists (select 1 from public.kount_price_fingerprints k where k.venue_id = t.venue_id and k.vendor_id is not distinct from t.vendor_id
          and k.gl_code is not distinct from t.gl_code and k.unit_cost = t.unit_cost and k.units_per_qty is not distinct from t.units_per_qty and k.master_item_id = d.live) then 'deleted' else 'moved' end, to_jsonb(t), d.id, d.live
  from public.kount_price_fingerprints t join _dead d on d.id = t.master_item_id;
delete from public.kount_price_fingerprints t using _dead d where d.id = t.master_item_id
   and exists (select 1 from public.kount_price_fingerprints k where k.venue_id = t.venue_id and k.vendor_id is not distinct from t.vendor_id
                 and k.gl_code is not distinct from t.gl_code and k.unit_cost = t.unit_cost and k.units_per_qty is not distinct from t.units_per_qty and k.master_item_id = d.live);
update public.kount_price_fingerprints t set master_item_id = d.live from _dead d where d.id = t.master_item_id;

-- ---- KevaOS tail via its own routine ----------------------------------------
do $$
declare r record;
begin
  for r in select d.id, d.live from _dead d
            where exists (select 1 from public.invoice_lines x where x.master_item_id = d.id)
               or exists (select 1 from public.menu_item_recipe_map x where x.master_item_id = d.id)
               or exists (select 1 from public.purchase_items x where x.master_item_id = d.id)
               or exists (select 1 from public.recipe_items x where x.master_item_id = d.id) loop
    perform public.repoint_master_refs(r.id, r.live, '0130');
  end loop;
end $$;

-- ---- check ------------------------------------------------------------------
do $$
declare left_n int;
begin
  select (select count(*) from public.kount_entries t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.kount_recounts t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.new_recipe_ingredient_master_map t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.kount_invoice_line_map t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.kount_invoice_item_map t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.kount_price_fingerprints t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.kount_venue_cost_overrides t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.kount_carried_items t join _dead d on d.id = t.master_item_id)
       + (select count(*) from public.invoice_lines t join _dead d on d.id = t.master_item_id)
    into left_n;
  if left_n > 0 then raise exception '0130: % rows still on merged-away items', left_n; end if;
end $$;

select table_name, action, count(*) n from public._mig0130_log group by 1, 2
union all
select 'kevaos via repoint_master_refs', table_name, count(*) from public.master_item_merge_repoints where reason = '0130' group by 2
order by 1, 2;
commit;
